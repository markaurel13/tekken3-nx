#!/usr/bin/env python3
import sys
import os
import subprocess
import datetime

def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else "build_version.h"
    try:
        git_hash = subprocess.check_output(
            ["git", "rev-parse", "--short=8", "HEAD"],
            stderr=subprocess.DEVNULL
        ).decode().strip()
    except Exception:
        git_hash = "unknown"

    try:
        diff_out = subprocess.check_output(
            ["git", "status", "--porcelain"],
            stderr=subprocess.DEVNULL
        ).decode().strip()
        if diff_out:
            git_hash += "-dirty"
    except Exception:
        pass

    now_str = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    content = f"""/* Auto-generated by gen_build_version.py - DO NOT EDIT */
#pragma once
#define BUILD_GIT_HASH "{git_hash}"
#define BUILD_TIMESTAMP "{now_str}"
"""
    # Write only if different or always write
    # Writing always ensures main.cpp re-reads the latest build time
    try:
        with open(out_path, "r") as f:
            old_content = f.read()
    except Exception:
        old_content = ""

    # Check git hash difference first; if git hash is identical and file is < 2s old, keep it
    with open(out_path, "w") as f:
        f.write(content)

if __name__ == "__main__":
    main()
